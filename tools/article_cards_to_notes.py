#!/usr/bin/env python3
"""Sync the daily article cards into the Polity notes (content-sync rule): every new mnemonic, and every case / amendment / fact the cards
flagged as missing from the notes (notes_gap), becomes a 'CARD ·' block in the chapter the card links to. Mnemonics that exist in only one
format go into the other format only. Writes src-gov/handnotes/found/polity/cn/cn_zz_artcards.py (rerun after editing data/article_cards.json)."""
import os, re, json, glob, html
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
A = json.load(open(os.path.join(R, 'data/article_cards.json'), encoding='utf8'))
HWTXT = {}
for f in glob.glob(os.path.join(R, 'src-gov/handnotes/found/polity/ch_*.py')) + glob.glob(os.path.join(R, 'src-gov/handnotes/found/polity/cn/cn_g*.py')):
    HWTXT[f] = open(f, encoding='utf8').read()
HWALL = '\n'.join(HWTXT.values())
def tbtext(cid):
    p = os.path.join(R, 'pol-ch%02d.html' % cid)
    s = open(p, encoding='utf8').read() if os.path.exists(p) else ''
    s = re.sub(r'<!--cn-->.*?<!--/cn-->', '', s, flags=re.S)
    return html.unescape(re.sub(r'<[^>]+>', ' ', s))
def plain(s): return html.unescape(re.sub(r'<[^>]+>', '', s))
def toks(name):
    w = re.findall(r'[A-Z][a-zA-Z\.]{2,}', re.sub(r'\bv\.?\b|Union of India|State of|India', '', name))
    return [x for x in w if x not in ('The', 'Union', 'State', 'Ltd', 'Pvt', 'Others', 'And', 'Re')][:2]
def chap(x):
    m = re.match(r'pol-ch(\d+)', x['link'][0]); return int(m.group(1)) if m else 14
def srcchap(src):
    m = re.search(r'Ch (\d+)', src); return int(m.group(1)) if m else None
OUT = {}; seen = set(); stats = {'blocks': 0, 'mn_new': 0, 'mn_tb': 0, 'mn_hw': 0, 'cases': 0, 'facts': 0}
def add(cid, nodes, only=None):
    b = {'after': '', 'nodes': nodes}
    if only: b['only'] = only
    OUT.setdefault(cid, []).append(b); stats['blocks'] += 1
order = sorted(A, key=lambda n: (int(re.match(r'\d+', n).group(0)), n))
for n in order:
    x = A[n]; cid = chap(x); nodes = []; title = plain(re.sub(r'\*\*', '', '')) 
    gaps = x.get('notes_gap', []); used = set()
    if any(re.search(r'not (covered|explained)|one-line mention', g) for g in gaps):
        kids = [plain(x['about'])] + ['<b>%s</b>: %s' % (c, d) for c, d in x.get('clauses', [])]
        nodes.append(('tree', '<b>Art %s</b>' % n, kids, None, 22)); used.add('about')
    for c in x.get('key', []):
        hit = [g for g in gaps if not g.startswith('FACT:') and any(t in g for t in toks(c['c']))]
        if hit:
            used.update(hit); stats['cases'] += 1
            nodes.append(('tree', '<b>%s</b> (%s)' % (c['c'], c['y']), ['<b>Issue:</b> %s' % c['issue'], '<b>Held:</b> %s' % c['held']], None, 24))
    for c in x.get('minor', []):
        hit = [g for g in gaps if not g.startswith('FACT:') and any(t in g for t in toks(c['c']))]
        if hit:
            used.update(hit); stats['cases'] += 1
            nodes.append(('bx', 'bl', '<b>%s</b> (%s): %s' % (c['c'], c['y'], c['pt'])))
    for a in x.get('amend', []):
        m = re.search(r'\b(\d+)(st|nd|rd|th)\b', a[0])
        hit = [g for g in gaps if m and re.search(r'\b%s(st|nd|rd|th)\b' % m.group(1), g)]
        if hit:
            used.update(hit); nodes.append(('bx', 'bl', '<b>%s</b>: %s (Art %s)' % (a[0], a[1], n)))
    for g in gaps:
        if g not in used and not re.search(r'not (covered|explained)|one-line mention', g):
            stats['facts'] += 1; nodes.append(('bx', 'bl', g[5:] if g.startswith('FACT:') else '<b>Also:</b> %s' % g))
    for m in x.get('mn', []):
        key = (m['w'].lower())
        if m['src'] == 'new':
            if key in seen: continue
            seen.add(key)
            if m['w'] in HWALL and m['w'] in tbtext(cid): continue
            stats['mn_new'] += 1; nodes.append(('mn', m['w'], m['x'] + ' <i>(own mnemonic)</i>'))
        elif 'handwritten only' in m['src'] or 'textbook only' in m['src']:
            sc = srcchap(m['src']) or cid
            if (key, sc) in seen: continue
            seen.add((key, sc))
            if 'handwritten only' in m['src']:
                if m['w'] in tbtext(sc): continue
                add(sc, [('sec', 'CARD · Mnemonic for Art %s' % n, 'b'), ('mn', m['w'], m['x'])], only='tb'); stats['mn_tb'] += 1
            else:
                if m['w'] in HWALL: continue
                add(sc, [('sec', 'CARD · Mnemonic for Art %s' % n, 'b'), ('mn', m['w'], m['x'])], only='hw'); stats['mn_hw'] += 1
    if nodes:
        t = plain(re.sub(r'\*\*', '', [a for a in json.load(open(os.path.join(R, 'data/article_cards.json'), encoding='utf8')).get(n, {}).get('about', '')][0]))
        add(cid, [('sec', 'CARD · Art %s: cases, amendments, mnemonics' % n, 'b')] + nodes)
out = '# -*- coding: utf-8 -*-\n# GENERATED by tools/article_cards_to_notes.py from data/article_cards.json. Do not edit by hand.\nfrom dsl import *\nADD = ' + repr(OUT) + '\n'
open(os.path.join(R, 'src-gov/handnotes/found/polity/cn/cn_zz_artcards.py'), 'w', encoding='utf8').write(out)
print(stats, 'chapters', sorted(OUT))
